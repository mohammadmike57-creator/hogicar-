// Regenerates the instant-paint shell in index.html from the real homepage header + hero.
//
// Phones only paint once ~400 KB of JavaScript has loaded. The shell is a static copy of the
// homepage header and hero that paints straight from the HTML, then Home removes it the moment
// React mounts (see pages/Home.tsx). Re-run this after changing the header, hero or search box:
//
//   npm run build && PORT=3010 node server.mjs &
//   node scripts/generate-boot-shell.mjs http://localhost:3010/
//
// Needs Playwright (PLAYWRIGHT_PATH / CHROMIUM_PATH override the defaults below).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const url = process.argv[2] || 'http://localhost:3010/';
const pw = await import(process.env.PLAYWRIGHT_PATH || 'playwright').catch(() => import('/opt/node22/lib/node_modules/playwright/index.mjs'));
const browser = await pw.chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
await page.goto(url, { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);

const html = await page.evaluate(() => {
  const header = document.querySelector('header');
  const hero = document.querySelector('main section');
  if (!header || !hero) throw new Error('header or hero section not found');
  const format = (iso) => new Date(`${iso}T00:00:00`).toLocaleDateString('en-US', { weekday: 'short', day: 'numeric', month: 'short' });
  const iso = (days) => { const d = new Date(); d.setDate(d.getDate() + days); return d.toISOString().split('T')[0]; };
  const dates = [[format(iso(0)), 0], [format(iso(3)), 3]];
  const clean = (el) => {
    const c = el.cloneNode(true);
    c.querySelectorAll('[id]').forEach((n) => n.removeAttribute('id'));
    c.querySelectorAll('input').forEach((n) => n.setAttribute('tabindex', '-1'));
    // Dates are filled in by the inline script so the shell never shows a stale day.
    const walker = document.createTreeWalker(c, NodeFilter.SHOW_TEXT);
    const hits = [];
    while (walker.nextNode()) {
      const match = dates.find(([text]) => walker.currentNode.nodeValue.trim() === text);
      if (match) hits.push([walker.currentNode, match[1]]);
    }
    hits.forEach(([node, days]) => { const s = document.createElement('span'); s.setAttribute('data-bd', String(days)); node.replaceWith(s); });
    return c.outerHTML;
  };
  return clean(header) + `<main class="flex-grow"><div class="bg-white font-sans text-slate-900">${clean(hero)}</div></main>`;
});
await browser.close();

const script = `(function(){try{if(location.pathname!=='/')return;var t=document.getElementById('boot-shell-tpl');if(!t)return;var d=document.createElement('div');d.id='boot-shell';d.setAttribute('inert','');d.setAttribute('aria-hidden','true');d.className='min-h-screen flex flex-col bg-slate-50 text-slate-900 text-base font-sans';d.style.cssText='position:absolute;top:0;left:0;right:0;z-index:60;min-height:0';d.appendChild(t.content.cloneNode(true));var f=function(n){var x=new Date();x.setDate(x.getDate()+n);return new Date(x.toISOString().split('T')[0]+'T00:00:00').toLocaleDateString('en-US',{weekday:'short',day:'numeric',month:'short'})};var b=d.querySelectorAll('[data-bd]');for(var i=0;i<b.length;i++){b[i].textContent=f(+b[i].getAttribute('data-bd'))}document.body.appendChild(d);setTimeout(function(){var s=document.getElementById('boot-shell');if(s)s.remove()},15000)}catch(e){}})();`;
const block = `<!-- boot-shell:start (generated by scripts/generate-boot-shell.mjs) -->\n    <template id="boot-shell-tpl">${html}</template>\n    <script>${script}</script>\n    <!-- boot-shell:end -->`;

const indexPath = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'index.html');
let index = fs.readFileSync(indexPath, 'utf8');
const re = /<!-- boot-shell:start[\s\S]*?<!-- boot-shell:end -->/;
index = re.test(index) ? index.replace(re, block) : index.replace('<div id="root"></div>', `<div id="root"></div>\n    ${block}`);
fs.writeFileSync(indexPath, index);
console.log(`boot shell written (${(block.length / 1024).toFixed(1)} KB)`);
